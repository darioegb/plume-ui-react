/**
 * This is the default RadioGroup. Use **defaultValue** to select a radio at first.
 */
export const Default: Story = {}

/**
 * Use **orientation** to lay the radios out in a row.
 */
export const Horizontal: Story = {
  args: {
    orientation: 'horizontal',
  },
}

function ControlledPlan(): React.ReactNode {
  const [plan, setPlan] = useState('pro')
  return (
    <div className="flex flex-col gap-3">
      <RadioGroup aria-label="Plan" onChange={setPlan} value={plan}>
        <Radio value="free">Free</Radio>
        <Radio value="pro">Pro</Radio>
        <Radio value="team">Team</Radio>
      </RadioGroup>
      <p>Selected plan: {plan}</p>
    </div>
  )
}

/**
 * Pass **value** and **onChange** to control the selection. **onChange** receives the new value.
 */
export const Controlled: Story = {
  render: () => <ControlledPlan />,
}

