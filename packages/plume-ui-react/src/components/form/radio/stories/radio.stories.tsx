/**
 * A radio to pick one option out of a few. It renders a native `<input type="radio">`, so it works with forms,
 * labels and the keyboard out of the box. Children become its label, and the `ref` points to the input.
 * Radios that share a **name** form a group, and the arrow keys move the selection between them.
 *
 * ### RadioGroup
 *
 * Wrap the radios in a `RadioGroup` to manage the group in one place. It owns the value, so you set it once with
 * **value** or **defaultValue** and listen to **onChange**, and it shares the name, size, color scheme, variant
 * and state with its radios. Inside a `Field`, the group is named by the Field's label.
 *
 * | Prop | Description |
 * | --- | --- |
 * | `value`, `defaultValue` | Value of the selected radio, for a controlled or an uncontrolled group. |
 * | `onChange` | Called with the value of the radio the user selects, and the change event. |
 * | `name` | Name shared by the radios. A unique one is generated by default. |
 * | `orientation` | `vertical` (default) or `horizontal`. |
 * | `size`, `colorScheme`, `variant` | Shared by the radios. A radio can set its own. |
 * | `disabled`, `readOnly`, `required` | State of the whole group. `readOnly` also silences `onChange`. |
 * | `aria-label`, `aria-labelledby`, `aria-describedby`, `aria-invalid` | Name, description and invalid state of the group. Inside a Field they come from it. |
 * | `className`, `style`, `id`, `children` | The usual. `children` are the `Radio` buttons, each one with a `value`. |
 */
